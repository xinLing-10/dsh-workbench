import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, cp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

test('the shipped worker loads outside the repository with no sibling packages', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'manager-packed-'));
  try {
    for (const file of ['index.mjs', 'lib', 'package.json']) {
      await cp(new URL('../' + file, import.meta.url), join(directory, file), { recursive: true });
    }
    const shipped = await import(pathToFileURL(join(directory, 'index.mjs')).href);
    assert.equal(typeof shipped.apply, 'function');
    assert.equal(typeof (await import(pathToFileURL(join(directory,'lib/runner.mjs')).href)).createWorkerRunner,'function');
    assert.equal(typeof (await import(pathToFileURL(join(directory,'lib/server.mjs')).href)).createWorkerServer,'function');
    assert.equal(typeof (await import(pathToFileURL(join(directory,'lib/isolation.mjs')).href)).createDockerSandbox,'function');
    assert.equal(typeof (await import(pathToFileURL(join(directory,'lib/isolated-runtime.mjs')).href)).createIsolatedRuntime,'function');
    const generated = await readFile(new URL('../lib/token-contract.mjs', import.meta.url), 'utf8');
    const canonical = await readFile(new URL('../../../packages/manager-contracts/tokens.mjs', import.meta.url), 'utf8');
    assert.equal(generated, '// Generated by scripts/sync-contracts.mjs; edit packages/manager-contracts/tokens.mjs.\n' + canonical);
    const question = await readFile(new URL('../lib/question-contract.mjs', import.meta.url), 'utf8');
    const questionSource = await readFile(new URL('../../../packages/manager-contracts/questions.mjs', import.meta.url), 'utf8');
    assert.equal(question, '// Generated by scripts/sync-contracts.mjs; edit packages/manager-contracts/questions.mjs.\n' + questionSource);
    const worker = await readFile(new URL('../lib/worker-contract.mjs', import.meta.url),'utf8');
    const workerSource = await readFile(new URL('../../../packages/manager-contracts/worker.mjs', import.meta.url),'utf8');
    assert.equal(worker,'// Generated by scripts/sync-contracts.mjs; edit packages/manager-contracts/worker.mjs.\n'+workerSource);
  } finally { await rm(directory, { recursive: true, force: true }); }
});
