import { readFile, writeFile } from 'node:fs/promises';
for (const [sourceName, targetName] of [['tokens', 'token'], ['questions', 'question'], ['worker','worker'], ['artifact-name','artifact-name'], ['requirements-policy','requirements-policy'], ['learning-policy','learning-policy']]) {
  const source = new URL(sourceName.endsWith('-policy') ? `../../../dsh-workbench/core/${sourceName}.js` : `../../../packages/manager-contracts/${sourceName}.mjs`, import.meta.url);
  const target = new URL(`../lib/${targetName}-contract.mjs`, import.meta.url);
  const generated = `// Generated by scripts/sync-contracts.mjs; edit ${sourceName.endsWith('-policy')?`dsh-workbench/core/${sourceName}.js`:`packages/manager-contracts/${sourceName}.mjs`}.\n` + await readFile(source, 'utf8');
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== generated) throw new Error('Worker contract is stale: run npm run contracts:sync');
  } else await writeFile(target, generated);
}
